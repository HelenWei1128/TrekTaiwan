export const TRAILS: Trail[] = RAW_TRAILS.map((raw) => {
  const path = densifyPath(raw.waypoints, 8);
  return {
    ...raw,
    path,
    distanceKm: Math.round(totalPathDistanceKm(raw.waypoints) * 10) / 10 || raw.elevationKeyPoints.at(-1)!.distanceKm,
    elevationProfile: raw.elevationKeyPoints,
  };
});

export function getTrailById(id: string): Trail | undefined {
  return TRAILS.find((t) => t.id === id);
}

